// Run: cd tools && npm install && node build-assets.mjs
// Writes favicons into ../ (site root) and the icon helper into ../assets/js/icons.js
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import pngToIco from 'png-to-ico';
import * as si from 'simple-icons';

const ROOT = path.resolve(process.cwd(), '..');          // site root: change if the site is served from a subfolder
const brand = (f) => readFileSync(path.join(ROOT, 'assets/brand', f));
const png = (buf, size) => sharp(buf, { density: 512 }).resize(size, size).png().toBuffer();

// ---------- Favicons ----------
const mark = brand('mark.svg');
const square = brand('mark-square.svg');
const maskable = brand('mark-maskable.svg');

writeFileSync(path.join(ROOT, 'favicon.svg'), mark);
const p16 = await png(mark, 16), p32 = await png(mark, 32), p48 = await png(mark, 48);
writeFileSync(path.join(ROOT, 'favicon-32.png'), p32);
writeFileSync(path.join(ROOT, 'favicon.ico'), await pngToIco([p16, p32, p48]));
writeFileSync(path.join(ROOT, 'apple-touch-icon.png'), await png(square, 180));
writeFileSync(path.join(ROOT, 'icon-192.png'), await png(mark, 192));
writeFileSync(path.join(ROOT, 'icon-512.png'), await png(mark, 512));
writeFileSync(path.join(ROOT, 'icon-maskable-512.png'), await png(maskable, 512));

// ---------- Icons ----------
const lucideDir = path.join(process.cwd(), 'node_modules/lucide-static/icons');
const lucideNames = ['mail','file-text','arrow-up-right','arrow-up','sun','moon','menu','x','copy','check',
  'award','circle-check','map-pin','terminal','code-xml','link','external-link','clock','chevron-right','download'];
const stroke = {};
for (const n of lucideNames) {
  const f = path.join(lucideDir, `${n}.svg`);
  if (!existsSync(f)) { console.warn('missing lucide icon:', n); continue; }
  stroke[n] = readFileSync(f, 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .trim();
}

// Brand glyphs from Simple Icons (single-colour, 24x24). Fallback path kept for LinkedIn in case it is not in the package.
const LINKEDIN_FALLBACK = 'M20.447 20.452h-3.554v-5.569c0-1.328-.027-3.037-1.852-3.037-1.853 0-2.136 1.445-2.136 2.939v5.667H9.351V9h3.414v1.561h.046c.477-.9 1.637-1.85 3.37-1.85 3.601 0 4.267 2.37 4.267 5.455v6.286zM5.337 7.433c-1.144 0-2.063-.926-2.063-2.065 0-1.138.92-2.063 2.063-2.063 1.14 0 2.064.925 2.064 2.063 0 1.139-.925 2.065-2.064 2.065zm1.782 13.019H3.555V9h3.564v11.452zM22.225 0H1.771C.792 0 0 .774 0 1.729v20.542C0 23.227.792 24 1.771 24h20.451C23.2 24 24 23.227 24 22.271V1.729C24 .774 23.2 0 22.222 0h.003z';
const brandMap = { github: 'siGithub', linkedin: 'siLinkedin', leetcode: 'siLeetcode', geeksforgeeks: 'siGeeksforgeeks',
  codeforces: 'siCodeforces', codechef: 'siCodechef', kaggle: 'siKaggle', hackerrank: 'siHackerrank',
  'x-twitter': 'siX', instagram: 'siInstagram', youtube: 'siYoutube' };
const brands = {};
for (const [key, exp] of Object.entries(brandMap)) {
  if (si[exp]) brands[key] = si[exp].path;
  else if (key === 'linkedin') brands[key] = LINKEDIN_FALLBACK;
  else console.warn('missing brand icon:', key);
}

const out = `/* GENERATED by tools/build-assets.mjs. Do not edit by hand. */
(function () {
  var STROKE = ${JSON.stringify(stroke)};
  var BRAND = ${JSON.stringify(brands)};
  var HOSTS = { 'github.com':'github','linkedin.com':'linkedin','leetcode.com':'leetcode','geeksforgeeks.org':'geeksforgeeks',
    'codeforces.com':'codeforces','codechef.com':'codechef','kaggle.com':'kaggle','hackerrank.com':'hackerrank',
    'x.com':'x-twitter','twitter.com':'x-twitter','instagram.com':'instagram','youtube.com':'youtube' };
  function svg(name, o) {
    o = o || {};
    var size = o.size || 20, cls = 'icon' + (o.cls ? ' ' + o.cls : '');
    if (BRAND[name]) {
      return '<svg class="' + cls + ' icon--brand" viewBox="0 0 24 24" width="' + size + '" height="' + size +
        '" fill="currentColor" aria-hidden="true" focusable="false"><path d="' + BRAND[name] + '"/></svg>';
    }
    if (STROKE[name]) {
      return '<svg class="' + cls + ' icon--stroke" viewBox="0 0 24 24" width="' + size + '" height="' + size +
        '" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' +
        STROKE[name] + '</svg>';
    }
    return '';
  }
  function forUrl(url) {
    try {
      var h = new URL(url, location.href).hostname.replace(/^www\\./, '');
      if (url.indexOf('mailto:') === 0) return 'mail';
      return HOSTS[h] || 'link';
    } catch (e) { return url && url.indexOf('mailto:') === 0 ? 'mail' : 'link'; }
  }
  window.Icons = { svg: svg, forUrl: forUrl };
})();
`;
mkdirSync(path.join(ROOT, 'assets/js'), { recursive: true });
writeFileSync(path.join(ROOT, 'assets/js/icons.js'), out);
console.log('Done.');
